export const CHARACTERS_LIST: Character[] = [
  CHARACTERS_MAP.twilight_sparkle,
  CHARACTERS_MAP.rainbow_dash,
  CHARACTERS_MAP.pinkie_pie,
  CHARACTERS_MAP.fluttershy,
  CHARACTERS_MAP.rarity,
  CHARACTERS_MAP.applejack,
];

/**
 * Crucial runtime integrity verification function
 * Guarantees 100% that characterId, name, and image match the single source of truth!
 */
export function verifyCharacterIntegrity(character: Partial<Character> | null | undefined): boolean {
  if (!character || !character.characterId) return false;
  const canonical = CHARACTERS_MAP[character.characterId as CharacterId];
  if (!canonical) return false;

  const nameMatches = character.name === canonical.name;
  const imageMatches = character.image === canonical.image;
  return nameMatches && imageMatches;
}

/**
 * Safely resolves character by characterId, preventing any accidental mismatch
 */
export function getVerifiedCharacter(characterId: CharacterId): Character {
  const char = CHARACTERS_MAP[characterId];
  if (!char) {
    // Fallback safe guard
    return CHARACTERS_MAP.twilight_sparkle;
  }
  return char;
}
